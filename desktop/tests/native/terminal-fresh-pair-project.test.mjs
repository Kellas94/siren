// Literal path-boundary regression only; never imports/executes either runtime.
import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {win32 as path} from 'node:path';
import vm from 'node:vm';

const read=name=>readFileSync(new URL(name,import.meta.url),'utf8');
const provisioner=read('./terminal-fresh-runtime-provision.mjs');
const driver=read('./terminal-fresh-pair-driver.mjs');
const worker=read('./terminal-fresh-pair-worker.mjs');
const buildSuffix=provisioner.match(/projectDirectory:path\.join\(job,('[^']+')\)/)?.[1];
const driverBoundary=driver.split('\n').find(line=>line.includes('const project=provision.projectDirectory;'));
const workerBoundary=worker.split('\n').find(line=>line.includes('const project=projectDirectory;'));
assert.ok(buildSuffix&&driverBoundary&&workerBoundary,'literal source boundaries required');
const jobRoot='C:\\siren-owned\\fresh-job';
const genuinePath=vm.runInNewContext(`path.join(job,${buildSuffix})`,{path,job:jobRoot},{timeout:200});
function inspect(projectDirectory){
 return vm.runInNewContext(driverBoundary,{assert,path,provision:{jobRoot,projectDirectory}},{timeout:200});
}
test('driver accepts the exact Unicode path generated by the genuine provisioner',()=>{
 assert.equal(genuinePath,path.join(jobRoot,'project-\u0218iren-\u0394'));
 assert.doesNotThrow(()=>inspect(genuinePath));
});
test('driver refuses the former corrupt encoding even inside the same owned job',()=>{
 assert.throws(()=>inspect(path.join(jobRoot,'project-\u00c8\u02dciren-\u00ce\u201d')),assert.AssertionError);
});
test('driver refuses another job and does not replace Unicode with an ASCII alias',()=>{
 for(const candidate of [path.join('C:\\other-job','project-\u0218iren-\u0394'),path.join(jobRoot,'project-Siren-D')]){
  assert.throws(()=>inspect(candidate),assert.AssertionError);
 }
});
test('retained worker accepts the same genuine provisioner path',()=>{
 assert.doesNotThrow(()=>vm.runInNewContext(workerBoundary,{assert,join:path.join,projectDirectory:genuinePath,retainedJobRoot:path.join(jobRoot,'retained')},{timeout:200}));
});
