// Known-refusal regressions over actual production backend/creator/ownership.
// Immutable fixture doubles native handles/byte I/O/PTY only. No shell, native
// addon, Electron, PIN, TerminalPolicy or product runtime admission is exercised.
import test from 'node:test';
import assert from 'node:assert/strict';
import {createInertProductionComposition,inertConfig,inertTick} from './fixtures/terminal-production-inert.mjs';
import {decodeTerminalCommandRequest,validateTerminalCommandReply} from '../src/terminal/command-protocol.mjs';

const count=(s,name)=>s.state.trace.filter(row=>row.name===name).length;
const lease=(ownerId,generation=1)=>({ownerId,windowId:'window1',epoch:4,leaseId:`lease${generation}`,generation});
const input=(ownerId,generation,data)=>({ownerId,leaseId:`lease${generation}`,generation,inputSequence:0,data});
const commands=s=>s.group('session1').creator.stats().session.commands;
const startup=s=>s.group('session1').creator.stats().session.startup;
async function waitUntil(predicate,label){for(let n=0;n<300&&!predicate();n++)await inertTick();assert(predicate(),label);}
async function tickTwice(){await inertTick();await inertTick();}
async function ready(s){
 const config=inertConfig();assert.equal((await s.backend.sendGate({generation:1,open:true})).ok,true);
 const p=s.backend.prepare(config,s.guard);assert.equal(p.ok,true);assert.equal(s.backend.allocate({ownerId:p.ownerId}).ok,true);
 assert.equal((await s.backend.connect({ownerId:p.ownerId},s.guard)).ok,true);
 return {p,config,initialStartup:startup(s),spawn:s.state.spawns[0]};
}
function survives(s,r){
 assert.equal(count(s,'native-stop'),0,'known admission/Lock refusal must not interrupt existing work');
 assert.equal(s.backend.stats().ready,1,'the same Session must remain ready after a known refusal');
 assert.equal(s.ownership.assertSessionCurrent({sessionOwnerId:r.p.ownerId}),true);
 assert.equal(r.config.admissionEpoch,4);assert.deepEqual(startup(s),r.initialStartup);
 assert.equal(s.state.spawns.length,1);assert.equal(s.state.spawns[0],r.spawn);assert.equal(s.state.loads,1);
 assert.equal(s.backend.nativeExecutionAdmitted,false);
}
async function installAndWrite(s,p,generation,data){
 assert.equal((await s.backend.install(lease(p.ownerId,generation),s.guard)).ok,true);
 assert.equal((await s.backend.input(input(p.ownerId,generation,data),s.guard)).accepted,true);
}
// Inspect a copied frame generated by real channel code while the inert native
// write is held. No callback, channel method, native DATA or wire is replaced.
function heldFrame(s,side){
 const pending=s.group('session1').lanes.command.writes[side];assert(pending,'actual held command-lane write required');
 const frame=Buffer.from(pending.bytes);assert(frame.length>=5);const bytes=frame.readUInt32BE(0);
 assert(bytes>0&&bytes<=32768);assert.equal(frame.length,bytes+4);
 return JSON.parse(frame.subarray(4).toString('utf8'));
}

test('already CLOSED gate refuses install without Stop or generation consumption and reuses Session after OPEN',async()=>{
 const s=createInertProductionComposition();try{
  const r=await ready(s);assert.equal((await s.backend.sendGate({generation:2,open:false})).ok,true);
  assert.equal(commands(s).gateOpen,false);assert.equal(commands(s).gateGeneration,2);
  assert.equal((await s.backend.install(lease(r.p.ownerId,7),s.guard)).ok,false);await tickTwice();
  assert.equal(commands(s).lastLeaseGeneration,0);assert.deepEqual(s.state.writes,[]);survives(s,r);
  assert.equal((await s.backend.sendGate({generation:3,open:true})).ok,true);
  await installAndWrite(s,r.p,1,'fresh after already closed refusal');
  assert.deepEqual(s.state.writes,['fresh after already closed refusal']);survives(s,r);
 }finally{s.releaseWrites();await s.dispose();}
});

